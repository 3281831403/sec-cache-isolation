"""Red tests for tenant-isolated cache keys.

Ten defect tests map one-to-one to the ten defects described in README.md.
Five additional tests cover the happy path, cross-tenant misses, separator
escaping, invalidation scope, and batch independence.  Do not edit this file
while solving the task.
"""

import pytest

from cachekey import (
    build_key,
    escape_part,
    invalidate,
    key_batch,
    parse_key,
    scope_ok,
    tenant_prefix,
    validate_policy,
)

GOOD_POLICY = {
    "require_tenant_prefix": True,
    "escape_parts": True,
    "allow_global_invalidation": False,
}


def test_defect01_missing_tenant_prefix():
    acme_key = build_key("acme", ["order:1"])
    beta_key = build_key("beta", ["order:1"])

    assert acme_key.startswith(tenant_prefix("acme"))
    assert beta_key.startswith(tenant_prefix("beta"))
    assert acme_key != beta_key


def test_defect02_prefix_boundary_has_separator():
    prefix = tenant_prefix("acme")

    assert prefix == tenant_prefix("acme")
    assert prefix.endswith(":")
    assert scope_ok(build_key("acme", ["order:1"]), "acme") is True
    assert scope_ok(build_key("acme2", ["order:1"]), "acme") is False


def test_defect03_separator_in_part_is_escaped():
    key = build_key("acme", ["order:1"])

    assert key.count(":") == 2
    assert parse_key(key)["parts"] == ["order:1"]


def test_defect04_control_characters_in_part_are_escaped():
    raw = "line\nbreak\tend\x00"
    escaped = escape_part(raw)

    assert escaped != raw
    assert "\n" not in escaped
    assert "\t" not in escaped
    assert all(ord(ch) >= 0x20 and ord(ch) != 0x7F for ch in escaped)


def test_defect05_parse_rejects_wrong_segment_count():
    with pytest.raises(ValueError):
        parse_key("acme:2:order")

    with pytest.raises(ValueError):
        parse_key("acme:1:order:extra")


def test_defect06_scope_check_rejects_prefix_lookalike():
    assert scope_ok(build_key("acme", ["order:1"]), "acme") is True
    assert scope_ok("acmex:1:order", "acme") is False
    assert scope_ok("acme2:1:order", "acme") is False
    assert scope_ok("acme:2:order", "acme") is False


def test_defect07_invalidate_pattern_does_not_cross_tenant():
    store = {
        build_key("acme", ["order:1"]): "acme-order",
        build_key("acme2", ["order:1"]): "acme2-order",
        build_key("beta", ["order:1"]): "beta-order",
    }

    removed = invalidate(store, "acme", "*")

    assert removed == 1
    assert len(store) == 2
    assert build_key("acme2", ["order:1"]) in store
    assert build_key("beta", ["order:1"]) in store


def test_defect08_invalidate_count_is_tenant_scoped():
    store = {
        build_key("acme", ["order:1"]): 1,
        build_key("acme", ["order:2"]): 2,
        build_key("acme2", ["order:1"]): 3,
        build_key("beta", ["order:1"]): 4,
    }

    removed = invalidate(store, "acme", "order:*")

    assert removed == 2
    assert len(store) == 2
    assert build_key("acme2", ["order:1"]) in store
    assert build_key("beta", ["order:1"]) in store


def test_defect09_policy_rejects_global_invalidation():
    issues = validate_policy(
        {
            "require_tenant_prefix": True,
            "escape_parts": True,
            "allow_global_invalidation": True,
        }
    )

    assert issues.count("global_invalidation_allowed") == 1
    assert validate_policy(GOOD_POLICY) == []


def test_defect10_batch_keeps_each_tenant_prefix():
    requests = [
        {"request_id": "first", "tenant": "acme", "parts": ["order:1"]},
        {"request_id": "second", "tenant": "beta", "parts": ["order:1"]},
    ]

    built = key_batch(requests, GOOD_POLICY)

    assert built["first"] == build_key("acme", ["order:1"])
    assert built["second"] == build_key("beta", ["order:1"])
    assert built["first"] != built["second"]
    assert scope_ok(built["second"], "beta") is True
    assert scope_ok(built["second"], "acme") is False


def test_roundtrip_tenant_and_parts():
    tenant = "租户A"
    parts = ["order:1", "item 2", "50%"]

    parsed = parse_key(build_key(tenant, parts))

    assert parsed["tenant"] == tenant
    assert parsed["parts"] == parts


def test_cross_tenant_key_is_not_in_scope():
    acme_key = build_key("acme", ["order:1"])
    beta_key = build_key("beta", ["order:1"])

    assert scope_ok(acme_key, "acme") is True
    assert scope_ok(beta_key, "acme") is False
    assert scope_ok(beta_key, "acme2") is False
    assert parse_key(beta_key)["tenant"] == "beta"


def test_part_separator_is_escaped_and_roundtrips():
    escaped = escape_part("a:b")

    assert ":" not in escaped
    assert escape_part("%") != "%"
    assert parse_key(build_key("acme", ["a:b"]))["parts"] == ["a:b"]


def test_invalidate_affects_only_current_tenant():
    store = {
        build_key("acme", ["order:1"]): 1,
        build_key("acme", ["order:2"]): 2,
        build_key("acme", ["profile:1"]): 3,
        build_key("beta", ["order:1"]): 4,
    }

    removed = invalidate(store, "acme", "order:*")

    assert removed == 2
    assert len(store) == 2
    assert build_key("acme", ["profile:1"]) in store
    assert build_key("beta", ["order:1"]) in store


def test_batch_matches_individual_builds():
    requests = [
        {"request_id": "one", "tenant": "acme", "parts": ["order:1"]},
        {"request_id": "two", "tenant": "acme", "parts": ["order:2"]},
        {"request_id": "three", "tenant": "beta", "parts": ["order:1"]},
    ]

    built = key_batch(requests, GOOD_POLICY)
    expected = {
        request["request_id"]: build_key(request["tenant"], request["parts"])
        for request in requests
    }

    assert built == expected
    assert len(built) == 3